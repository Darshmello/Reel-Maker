// Scan src/sets/<id>/ (index.ts + meta.json) and write src/sets/registry.ts with static imports, so
// Remotion's bundler sees every pack. Run before bundling; render.ps1 and the studio do it for you.
// usage: node scripts/sets-registry.mjs   -> prints the ids it registered
import {existsSync, readdirSync, readFileSync, writeFileSync} from 'node:fs';
import {join, resolve} from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const DIR = join(ROOT, 'src', 'sets');
export const listSets = () =>
  readdirSync(DIR, {withFileTypes: true})
    .filter((d) => d.isDirectory() && existsSync(join(DIR, d.name, 'index.ts')) && existsSync(join(DIR, d.name, 'meta.json')))
    .map((d) => ({...JSON.parse(readFileSync(join(DIR, d.name, 'meta.json'), 'utf8')), id: d.name}))
    .sort((a, b) => (a.id === 'city-bridge' ? -1 : b.id === 'city-bridge' ? 1 : a.id.localeCompare(b.id)));

export const writeRegistry = () => {
  const sets = listSets();
  const id = (s) => s.id.replace(/[^a-zA-Z0-9]/g, '_');
  const src = `// Generated by scripts/sets-registry.mjs from src/sets/*/ (index.ts + meta.json). Do not edit.
import type {SetMeta, SetPack} from './types';
${sets.map((s) => `import {pack as ${id(s)}} from './${s.id}';`).join('\n')}

export const SETS: Record<string, {pack: SetPack; meta: SetMeta}> = {
${sets.map((s) => `  '${s.id}': {pack: ${id(s)}, meta: ${JSON.stringify(s)}},`).join('\n')}
};
export const DEFAULT_SET = 'city-bridge';
`;
  const out = join(DIR, 'registry.ts');
  if (!existsSync(out) || readFileSync(out, 'utf8') !== src) writeFileSync(out, src);
  return sets;
};

if (process.argv[1] && resolve(process.argv[1]) === resolve(import.meta.filename)) console.log(writeRegistry().map((s) => s.id).join(' '));
